def _validate_predecision_values(
    values: Mapping[str, object],
    *,
    trusted_certificate: Optional[
        CounterKeyedInitialTiltRejectionFactorizationClosureCertificate
    ] = None,
) -> None:
    certificate = values["certificate"]
    if trusted_certificate is None:
        checked = _validate_certificate(certificate)
    else:
        if certificate is not trusted_certificate:
            raise ValueError("CP43 predecision certificate identity differs")
        checked = trusted_certificate
    if values["certificate_sha256"] != checked.certificate_sha256:
        raise ValueError("CP43 predecision certificate digest differs")
    _EXACT_INTEGER(values["run_id"], name="predecision.run_id")
    _EXACT_INTEGER(
        values["initialization_index"], name="predecision.initialization_index"
    )
    status = values["status"]
    if type(status) is not str or status not in (
        INITIAL_TILT_REJECTION_FACTORIZATION_CLOSURE_PREDECISION_STATUSES
    ):
        raise ValueError("CP43 predecision status differs")
    words = _EXACT_WORDS(
        values["proposal_words"],
        name="predecision.proposal_words",
        length=checked.proposal_word_count,
    )
    if values["proposal_words"] is not words:
        raise ValueError("CP43 proposal words are not canonical")
    if values["proposal_words_sha256"] != _proposal_words_sha256(words):
        raise ValueError("CP43 proposal-word digest differs")
    parent = values["checkpoint42_result"]
    if status == "preparation_failure":
        if parent is not None or values["checkpoint42_result_sha256"] is not None:
            raise ValueError("F36 must not retain a CP42 result")
        expected_failure = True
    else:
        parent = _CP42_VALIDATE_PREDECISION_RECORD(
            parent,
            trusted_certificate=checked.checkpoint42_certificate,
        )
        if parent.status != status:
            raise ValueError("CP43 and CP42 predecision statuses differ")
        if parent.run_id != values["run_id"] or (
            parent.initialization_index != values["initialization_index"]
        ):
            raise ValueError("CP43 and CP42 request identities differ")
        if parent.proposal_words != words:
            raise ValueError("CP43 and CP42 proposal words differ")
        if values["checkpoint42_result_sha256"] != parent.result_sha256:
            raise ValueError("CP43 parent-result digest differs")
        expected_failure = False
    for name, expected in (
        ("typed_preparation_failure_totalized", expected_failure),
        ("failure_payload_discarded", expected_failure),
        ("v_only_input_consumed", True),
        ("decision_words_present", False),
    ):
        _EXACT_BOOL(values[name], expected, name="predecision." + name)
    _REQUIRE_SHA256(values["result_sha256"], name="predecision.result_sha256")
    if values["result_sha256"] != _SEMANTIC_DIGEST(_predecision_payload(values)):
        raise ValueError("CP43 predecision digest differs")


