"""Close the supplied-word factorization at an explicit reference boundary.

Checkpoint 43 binds one exact checkpoint-42 owner.  It totalizes only the
declared checkpoint-28 and checkpoint-30 operational error types as the
preparation-failure atom F36.  Checkpoint 42 already maps the exact
checkpoint-37 quota-certification error to F37.  Every other exception remains
a refusal.  Thus the supplied-word reference map is total only under the
declared typed-error and trusted-runtime contract; this is not a generic
exception catcher.

The resulting reference theorem is structural: G43 accepts V only, while the
semantic post-G kernel H43 accepts W only after G43 has produced F36, F37, or a
complete quota tuple.  The combined public entry point evaluates exactly that
composition once.  The separately invoked public H facade replays G for
custody before applying the semantic kernel, so its failure pass-through
requires replay-stable deterministic failures.  The theorem discharges the
abstract factorization only for this supplied-word reference semantics.  It
does not identify that semantics with every live checkpoint-36 or
checkpoint-37 failure, and it makes no live Philox distribution claim.

Natural F37 reachability is deliberately left unresolved.  Valid parent gaps
exclude every quota-error route except the final adaptive floor-separation
limit; the existing contracts provide neither a valid-parent counterexample
nor a uniform separation theorem.
"""

