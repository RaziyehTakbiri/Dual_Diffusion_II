def _qualification_failure(condition: bool, code: str, message: str) -> None:
    if not condition:
        raise CP68CompactProjectionAggregationQualificationError(code, message)


def _validate_projection(projection: object, logical_ordinal: int) -> dict:
    _qualification_failure(
        type(projection) is dict,
        "CP68_PROJECTION_TYPE_MISMATCH",
        "a compact projection is not an exact built-in mapping",
    )
    checked = cast(dict, projection)
    _qualification_failure(
        all(type(key) is str for key in checked)
        and set(checked) == set(_PROJECTION_KEYS),
        "CP68_PROJECTION_FIELD_SET_MISMATCH",
        "a compact projection has a non-frozen field set",
    )
    seed_ordinal = (logical_ordinal - 1) // CP68_TEST28_ROW_COUNT + 1
    row_ordinal = (logical_ordinal - 1) % CP68_TEST28_ROW_COUNT + 1
    fixture_id, strategy, budget = _ROW_SHAPES[row_ordinal - 1]
    status, first_attempt, selected = _projection_status(seed_ordinal, row_ordinal)
    feature_items = _row_feature_items(row_ordinal) if selected else ()
    expected = {
        "schema_version": CP68_TEST28_SCHEMA_VERSION,
        "seed_ordinal": seed_ordinal,
        "row_ordinal": row_ordinal,
        "logical_request_ordinal": logical_ordinal,
        "row_key": _row_key(row_ordinal),
        "fixture_id": fixture_id,
        "strategy": strategy,
        "budget": budget,
        "plan_seed_hex": "%016x" % (seed_ordinal - 1),
        "observable_cell_label": status,
        "first_selected_attempt_one_based": first_attempt,
        "selected": selected,
        "selected_feature_ids": tuple(item[0] for item in feature_items),
        "selected_feature_values": tuple(item[1] for item in feature_items),
    }
    exact_types = {
        "schema_version": str,
        "seed_ordinal": int,
        "row_ordinal": int,
        "logical_request_ordinal": int,
        "row_key": str,
        "fixture_id": str,
        "strategy": str,
        "budget": int,
        "plan_seed_hex": str,
        "observable_cell_label": str,
        "selected": bool,
        "selected_feature_ids": tuple,
        "selected_feature_values": tuple,
        "projection_sha256": str,
    }
    _qualification_failure(
        all(type(checked[name]) is wanted for name, wanted in exact_types.items())
        and (
            checked["first_selected_attempt_one_based"] is None
            or type(checked["first_selected_attempt_one_based"]) is int
        )
        and all(type(item) is str for item in checked["selected_feature_ids"])
        and all(type(item) is Fraction for item in checked["selected_feature_values"]),
        "CP68_PROJECTION_FIELD_TYPE_MISMATCH",
        "a compact projection field has a non-frozen exact type",
    )
    ordinal_fields = (
        "seed_ordinal",
        "row_ordinal",
        "logical_request_ordinal",
    )
    _qualification_failure(
        all(checked[name] == expected[name] for name in ordinal_fields),
        "CP68_PROJECTION_ORDINAL_MISMATCH",
        "a compact projection breaks seed-major logical order",
    )
    _qualification_failure(
        all(checked[name] == value for name, value in expected.items()),
        "CP68_PROJECTION_CONTENT_MISMATCH",
        "a compact projection differs from the closed synthetic fixture",
    )
    supplied_digest = checked["projection_sha256"]
    _qualification_failure(
        len(supplied_digest) == 64
        and all(character in "0123456789abcdef" for character in supplied_digest)
        and hmac.compare_digest(supplied_digest, _projection_digest(expected)),
        "CP68_PROJECTION_DIGEST_MISMATCH",
        "a compact projection digest differs from its exact body",
    )
    return checked


def _build_output_record(
    spec: dict,
    observable_counts: Mapping[tuple, int],
    first_attempt_counts: Mapping[tuple, int],
    selected_counts: Tuple[int, ...],
    feature_sums: Mapping[tuple, Fraction],
) -> CP68EstimandEstimateIntervalV1:
    family = spec["estimand_family"]
    row_ordinal = spec["row_ordinal"]
    if family == "observable-cell":
        success_count = observable_counts[(row_ordinal, spec["observable_cell_label"])]
