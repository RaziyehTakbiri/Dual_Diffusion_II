def _run_compact_projection_aggregation_qualification() -> CP68CompactProjectionAggregationQualificationV1:
    bundle = cp68_compact_projection_aggregation_qualification_bundle()
    expectation = bundle.aggregation_expectation
    outputs, metrics = _aggregate_closed_fixture_details()
    output_matches = (
        metrics["request_count"] == expectation.request_count
        and len(outputs) == expectation.estimand_count
        and metrics["selected_counts_by_row"] == expectation.selected_counts_by_row
        and hmac.compare_digest(
            metrics["ordered_projection_sha256"],
            expectation.ordered_projection_sha256,
        )
        and hmac.compare_digest(
            metrics["ordered_estimand_record_sha256s_sha256"],
            expectation.ordered_estimand_record_sha256s_sha256,
        )
        and hmac.compare_digest(
            metrics["output_body_sha256"], expectation.output_body_sha256
        )
        and metrics["output_canonical_json_bytes"]
        == expectation.output_canonical_json_bytes
        and hmac.compare_digest(
            metrics["output_canonical_json_sha256"],
            expectation.output_canonical_json_sha256,
        )
    )
    _qualification_failure(
        output_matches,
        "CP68_FROZEN_EXPECTATION_MISMATCH",
        "the closed aggregate differs from its frozen output expectation",
    )
    feature_outputs = tuple(
        item
        for item in outputs
        if item.estimand_family == "selected-conditional-feature"
    )
    feature_threshold_verified = all(
        (item.interval_state == "computed")
        == (item.denominator_count >= CP68_TEST28_MINIMUM_SELECTED_COUNT)
        and (item.estimate is None) == (item.denominator_count == 0)
        for item in feature_outputs
    )
    computed_features = tuple(
        item for item in feature_outputs if item.interval_state == "computed"
    )
    feature_clipping_verified = (
        bool(computed_features)
        and all(
            item.feature_lower_bound is not None
            and item.feature_upper_bound is not None
            and item.interval_lower is not None
            and item.interval_upper is not None
            and item.feature_lower_bound
            <= item.interval_lower
            <= item.interval_upper
            <= item.feature_upper_bound
            for item in computed_features
        )
        and any(
            item.interval_lower == item.feature_lower_bound
            or item.interval_upper == item.feature_upper_bound
            for item in computed_features
        )
    )
    cp_zero = _exact_clopper_pearson_interval(0)
    cp_all = _exact_clopper_pearson_interval(CP68_TEST28_SEED_COUNT)
    cp_golden = _cp_golden_endpoints_verified()
    all_checks = (
        metrics["logical_ordinals_complete"]
        and metrics["observable_row_sums"]
        == (CP68_TEST28_SEED_COUNT,) * CP68_TEST28_ROW_COUNT
        and metrics["rejection_first_attempt_row_sums"]
        == (2_048, 1_040, 1_039, 0, 0, 1_039, 1_040, 2_048)
        and metrics["feature_contribution_count"] == 321_906
        and metrics["aggregation_update_count"] == 362_928
        and metrics["feature_computed_count"] == 156
        and metrics["feature_insufficient_count"] == 156
        and cp_zero[0] == 0
        and 0 < cp_zero[1] < 1
        and 0 < cp_all[0] < 1
        and cp_all[1] == 1
        and cp_golden
        and feature_threshold_verified
        and feature_clipping_verified
        and output_matches
    )
    _qualification_failure(
        all_checks,
        "CP68_DEVELOPMENT_CHECK_MISMATCH",
        "one or more closed development qualification checks failed",
    )
    qualification = cast(
        CP68CompactProjectionAggregationQualificationV1,
        _record(
            CP68CompactProjectionAggregationQualificationV1,
            {
                "schema_version": CP68_TEST28_SCHEMA_VERSION,
                "fixture_set_sha256": expectation.fixture_set_sha256,
                "request_count": metrics["request_count"],
                "logical_ordinals_complete": (metrics["logical_ordinals_complete"]),
                "streaming_peak_projection_count": 1,
                "compact_projection_corpus_retained": False,
                "observable_row_sums_verified": True,
                "first_attempt_sums_verified": True,
                "feature_denominators_verified": True,
                "estimand_count": len(outputs),
                "binomial_interval_count": (CP68_TEST28_BINOMIAL_ESTIMAND_COUNT),
                "feature_interval_count": metrics["feature_computed_count"],
                "insufficient_selection_count": (metrics["feature_insufficient_count"]),
                "computed_interval_count": (
                    CP68_TEST28_BINOMIAL_ESTIMAND_COUNT
                    + metrics["feature_computed_count"]
                ),
                "cp_zero_endpoint_verified": True,
                "cp_all_endpoint_verified": True,
                "cp_256_step_dyadic_endpoints_independently_verified": (cp_golden),
                "feature_threshold_verified": feature_threshold_verified,
                "feature_clipping_verified": feature_clipping_verified,
                "ordered_projection_sha256": (metrics["ordered_projection_sha256"]),
                "ordered_estimand_record_sha256s_sha256": (
                    metrics["ordered_estimand_record_sha256s_sha256"]
                ),
                "output_body_sha256": metrics["output_body_sha256"],
                "output_canonical_json_bytes": (metrics["output_canonical_json_bytes"]),
                "output_canonical_json_sha256": (
                    metrics["output_canonical_json_sha256"]
                ),
                "output_matches_frozen_expectation": output_matches,
                "raw_or_stable_recomputation_performed": False,
                "decision_path_qualified": False,
                "production_evidence": False,
                "production_execution_authorized": False,
                "runner_and_recomputation_blocker_closed": False,
                "formal_test_28_closed": False,
                "all_development_qualification_checks_passed": all_checks,
            },
        ),
    )
    del outputs, feature_outputs, computed_features
    return qualification


_QUALIFICATION_LOCK = threading.RLock()


def cp68_run_compact_projection_aggregation_qualification() -> CP68CompactProjectionAggregationQualificationV1:
    """Run the closed zero-I/O qualification and return its compact receipt."""

    try:
        with _QUALIFICATION_LOCK:
            return _run_compact_projection_aggregation_qualification()
    except CP68CompactProjectionAggregationQualificationError:
        raise
    except MemoryError as exc:
        raise CP68CompactProjectionAggregationQualificationError(
            "CP68_RESOURCE_EXHAUSTED",
            "the closed CP68 qualification exceeded its memory boundary",
        ) from exc
    except Exception as exc:
        raise CP68CompactProjectionAggregationQualificationError(
            "CP68_QUALIFICATION_FAILURE",
            "the closed source-independent CP68 qualification failed",
        ) from exc


