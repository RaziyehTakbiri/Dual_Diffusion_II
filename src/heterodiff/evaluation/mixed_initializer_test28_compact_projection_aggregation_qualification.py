def _canonical_resource_violation() -> CP68CompactProjectionAggregationQualificationError:
    return CP68CompactProjectionAggregationQualificationError(
        "CP68_CANONICAL_RESOURCE_VIOLATION",
        "the CP68 canonical value exceeds its closed graph limits",
    )


def _plain_json_value(
    value: object,
    *,
    _depth: int = 0,
    _node_count: Optional[list[int]] = None,
    _canonical_byte_count: Optional[list[int]] = None,
    _active_container_ids: Optional[set[int]] = None,
    _maximum_bytes: int = CP68_TEST28_OUTPUT_MAX_BYTES,
) -> object:
    if _node_count is None:
        _node_count = [0]
    if _canonical_byte_count is None:
        _canonical_byte_count = [0]
    if _active_container_ids is None:
        _active_container_ids = set()
    _node_count[0] += 1
    if (
        _depth > _MAXIMUM_CANONICAL_DEPTH
        or _node_count[0] > _MAXIMUM_CANONICAL_NODE_COUNT
    ):
        raise _canonical_resource_violation()
    if value is None:
        _canonical_byte_count[0] += 4
        result: object = None
    elif type(value) is bool:
        _canonical_byte_count[0] += 4 if value else 5
        result = value
    elif type(value) is int:
        if cast(int, value).bit_length() > _MAXIMUM_CANONICAL_INTEGER_BITS:
            raise _canonical_resource_violation()
        _canonical_byte_count[0] += len(str(value))
        result = value
    elif type(value) is Fraction:
        fraction = cast(Fraction, value)
        if (
            fraction.numerator.bit_length() > _MAXIMUM_CANONICAL_INTEGER_BITS
            or fraction.denominator.bit_length() > _MAXIMUM_CANONICAL_INTEGER_BITS
        ):
            raise _canonical_resource_violation()
        result = {"$fraction": [str(fraction.numerator), str(fraction.denominator)]}
        _canonical_byte_count[0] += len(
            json.dumps(result, sort_keys=True, separators=(",", ":"))
        )
    elif type(value) is str:
        if len(cast(str, value)) > _MAXIMUM_CANONICAL_STRING_CHARACTERS:
            raise _canonical_resource_violation()
        _canonical_byte_count[0] += len(json.dumps(cast(str, value), ensure_ascii=True))
        result = value
    elif type(value) in (tuple, list, dict) or type(value) in _RECORD_DOMAINS:
        identity = id(value)
        if identity in _active_container_ids:
            raise _canonical_resource_violation()
        _active_container_ids.add(identity)
        try:
            if type(value) in (tuple, list):
                sequence = cast(tuple, value)
                _canonical_byte_count[0] += 2 + max(0, len(sequence) - 1)
                result = [
                    _plain_json_value(
                        item,
                        _depth=_depth + 1,
                        _node_count=_node_count,
                        _canonical_byte_count=_canonical_byte_count,
                        _active_container_ids=_active_container_ids,
                        _maximum_bytes=_maximum_bytes,
                    )
                    for item in sequence
                ]
            elif type(value) is dict:
                mapping = cast(dict, value)
                _canonical_byte_count[0] += 2 + max(0, len(mapping) - 1)
                built = {}
                for key, item in mapping.items():
                    if type(key) is not str:
                        raise TypeError("CP68 JSON object keys must be exact strings")
                    if len(key) > _MAXIMUM_CANONICAL_KEY_CHARACTERS:
                        raise _canonical_resource_violation()
                    _canonical_byte_count[0] += (
                        len(json.dumps(key, ensure_ascii=True)) + 1
                    )
                    built[key] = _plain_json_value(
                        item,
                        _depth=_depth + 1,
                        _node_count=_node_count,
                        _canonical_byte_count=_canonical_byte_count,
                        _active_container_ids=_active_container_ids,
                        _maximum_bytes=_maximum_bytes,
                    )
                result = built
            else:
                record_fields = fields(type(value))
                _canonical_byte_count[0] += 2 + max(0, len(record_fields) - 1)
                built = {}
                for item in record_fields:
                    _canonical_byte_count[0] += (
                        len(json.dumps(item.name, ensure_ascii=True)) + 1
                    )
                    built[item.name] = _plain_json_value(
                        getattr(value, item.name),
                        _depth=_depth + 1,
                        _node_count=_node_count,
                        _canonical_byte_count=_canonical_byte_count,
                        _active_container_ids=_active_container_ids,
                        _maximum_bytes=_maximum_bytes,
                    )
                result = built
        finally:
            _active_container_ids.remove(identity)
    else:
        raise TypeError("value has no CP68 canonical JSON representation")
    if _canonical_byte_count[0] > _maximum_bytes:
        raise _canonical_resource_violation()
    return result


def _plain_json_bytes(
    value: object, *, maximum_bytes: int = CP68_TEST28_OUTPUT_MAX_BYTES
) -> bytes:
    try:
        byte_count = [0]
        plain = _plain_json_value(
            value,
            _canonical_byte_count=byte_count,
            _maximum_bytes=maximum_bytes,
        )
        encoded = json.dumps(
            plain,
            sort_keys=True,
            separators=(",", ":"),
            ensure_ascii=True,
            allow_nan=False,
        ).encode("ascii")
        if len(encoded) != byte_count[0] or len(encoded) > maximum_bytes:
            raise _canonical_resource_violation()
        return encoded
    except RecursionError as exc:
        raise _canonical_resource_violation() from exc


def _record(cls: type, values: Mapping[str, object]) -> object:
    names = tuple(item.name for item in fields(cls))
    if set(values) != set(names) - {"record_sha256"}:
        raise TypeError("CP68 sealed record field set differs")
    complete = dict(values)
    complete["record_sha256"] = _ZERO_SHA256
    provisional = object.__new__(cls)
    for name in names:
        object.__setattr__(provisional, name, complete[name])
    complete["record_sha256"] = hashlib.sha256(
        _RECORD_DOMAINS[cls]
        + b"\0"
        + _plain_json_bytes(provisional, maximum_bytes=_MAXIMUM_CANONICAL_RECORD_BYTES)
    ).hexdigest()
    result = object.__new__(cls)
    for name in names:
        object.__setattr__(result, name, complete[name])
    snapshot = _plain_json_bytes(result, maximum_bytes=_MAXIMUM_CANONICAL_RECORD_BYTES)
    with _ISSUED_RECORD_LOCK:
        _ISSUED_RECORD_SNAPSHOTS[cast(_SealedRecord, result)] = snapshot
    return result


def _require_issued_record(value: object) -> _SealedRecord:
    if type(value) not in _RECORD_DOMAINS:
        raise TypeError("value must be an exact CP68 sealed record")
    record = cast(_SealedRecord, value)
    with _ISSUED_RECORD_LOCK:
        snapshot = _ISSUED_RECORD_SNAPSHOTS.get(record)
    if snapshot is None:
        raise TypeError("CP68 record was not module-created")
    if not hmac.compare_digest(
        snapshot,
        _plain_json_bytes(record, maximum_bytes=_MAXIMUM_CANONICAL_RECORD_BYTES),
    ):
        raise ValueError("CP68 record was mutated after issue")
    return record


def cp68_canonical_json_bytes(value: object) -> bytes:
    """Return canonical JSON bytes for one unchanged module-issued record."""

    return _plain_json_bytes(
        _require_issued_record(value),
        maximum_bytes=_MAXIMUM_CANONICAL_RECORD_BYTES,
    )


def cp68_sha256(value: object) -> str:
    """Return the public type-separated digest of an issued CP68 record."""

    record = _require_issued_record(value)
    return hashlib.sha256(
        b"cp68-public-record-v1\0"
        + type(record).__name__.encode("ascii")
        + b"\0"
        + cp68_canonical_json_bytes(record)
    ).hexdigest()


def _upper_tail_compare(success_count: int, probability_numerator: int) -> int:
    """Compare P[Binomial(2048,a/2**256)>=k] with 1/110800 exactly."""

    n = CP68_TEST28_SEED_COUNT
    k = success_count
    a = probability_numerator
    denominator = _CP_DENOMINATOR
    if k <= 0:
        return 1
    if k > n or a == 0:
        return -1
    if a == denominator:
        return 1
    complement = denominator - a
    threshold = _CP_COMMON_DENOMINATOR_POWER
    term = comb(n, k) * a**k * complement ** (n - k)
    partial = term
    index = k
    while True:
        left = partial * _CP_TAIL_RECIPROCAL
        if left > threshold:
            return 1
        if index == n:
            return (left > threshold) - (left < threshold)
        ratio_numerator = (n - index) * a
        ratio_denominator = (index + 1) * complement
        if ratio_numerator < ratio_denominator:
            gap = ratio_denominator - ratio_numerator
            bounded_left = (
                partial * gap + term * ratio_numerator
            ) * _CP_TAIL_RECIPROCAL
            if bounded_left < threshold * gap:
                return -1
        dividend = term * ratio_numerator
        term, remainder = divmod(dividend, ratio_denominator)
        if remainder:
            raise AssertionError("CP68 exact binomial recurrence differs")
        partial += term
        index += 1


def _decimal_upper_tail_and_derivative(
    success_count: int, probability: Decimal
) -> Tuple[Decimal, Decimal]:
    n = CP68_TEST28_SEED_COUNT
    k = success_count
    complement = Decimal(1) - probability
    coefficient = Decimal(comb(n, k))
    term = coefficient * probability**k * complement ** (n - k)
    total = term
    for index in range(k, n):
        term = (
            term * Decimal(n - index) * probability / (Decimal(index + 1) * complement)
        )
        total += term
        if not term:
            break
    derivative = (
        Decimal(k) * coefficient * probability ** (k - 1) * complement ** (n - k)
    )
    return total, derivative


def _decimal_candidate_lower_cp_numerator(success_count: int) -> int:
    """Compute a high-precision candidate that never decides an endpoint."""

    n = CP68_TEST28_SEED_COUNT
    k = success_count
    with localcontext() as context:
        context.prec = 120
        target = Decimal(1) / Decimal(_CP_TAIL_RECIPROCAL)
        sample = k / n
        z = NormalDist().inv_cdf(1.0 - 1.0 / _CP_TAIL_RECIPROCAL)
        z_squared = z * z
        center = (sample + z_squared / (2 * n)) / (1 + z_squared / n)
        spread = (
            z
            / (1 + z_squared / n)
            * (sample * (1 - sample) / n + z_squared / (4 * n * n)) ** 0.5
        )
        initial = max(2.0**-256, min(sample, center - spread))
        low = Decimal(0)
        high = Decimal(k) / Decimal(n)
        probability = Decimal(repr(initial))
        if not low < probability < high:
            probability = (low + high) / 2
        for _ in range(40):
            tail, derivative = _decimal_upper_tail_and_derivative(k, probability)
            if tail < target:
                low = probability
            else:
                high = probability
            candidate = (
                probability - (tail - target) / derivative
                if derivative
                else (low + high) / 2
            )
            if candidate == probability:
                break
            if not low < candidate < high:
                candidate = (low + high) / 2
            probability = candidate
        return int(probability * Decimal(_CP_DENOMINATOR))


def _approximate_lower_cp_numerator(success_count: int) -> int:
    """Return an untrusted search proposal for hostile-test substitution."""

    return _decimal_candidate_lower_cp_numerator(success_count)


@lru_cache(maxsize=CP68_TEST28_SEED_COUNT)
def _lower_cp_numerator(success_count: int) -> int:
    """Find the greatest dyadic numerator whose exact upper tail is < delta."""

    if not 1 <= success_count <= CP68_TEST28_SEED_COUNT:
        raise ValueError("positive success_count is outside 1..2048")
    guarded_candidate = _decimal_candidate_lower_cp_numerator(success_count)
    proposed_candidate = _approximate_lower_cp_numerator(success_count)
    if type(proposed_candidate) is not int:
        proposed_candidate = guarded_candidate
    if abs(proposed_candidate - guarded_candidate) > 1:
        proposed_candidate = guarded_candidate
    guess = max(
        0,
        min(
            _CP_DENOMINATOR - 1,
            proposed_candidate,
        ),
    )
    comparison = _upper_tail_compare(success_count, guess)
    if comparison < 0:
        low = guess
        step = 1
        while True:
            high = min(_CP_DENOMINATOR, low + step)
            if _upper_tail_compare(success_count, high) >= 0:
                break
            if high == _CP_DENOMINATOR:
                raise AssertionError("CP68 lower-bound bracket differs")
            low = high
            step *= 2
    else:
        high = guess
        step = 1
        while True:
            low = max(0, high - step)
            if _upper_tail_compare(success_count, low) < 0:
                break
            if low == 0:
                raise AssertionError("CP68 lower-bound bracket differs")
            high = low
            step *= 2
    while high - low > 1:
        mid = (low + high) // 2
        if _upper_tail_compare(success_count, mid) < 0:
            low = mid
        else:
            high = mid
    return low


@lru_cache(maxsize=CP68_TEST28_SEED_COUNT + 1)
def _exact_clopper_pearson_interval(
    success_count: int,
) -> Tuple[Fraction, Fraction]:
    """Return the frozen n=2048 exact 256-step outward interval."""

    if type(success_count) is not int:
        raise TypeError("success_count must be an exact integer")
    if not 0 <= success_count <= CP68_TEST28_SEED_COUNT:
        raise ValueError("success_count is outside the frozen range 0..2048")
    k = success_count
    lower_numerator = 0 if k == 0 else _lower_cp_numerator(k)
    upper_numerator = (
        _CP_DENOMINATOR
        if k == CP68_TEST28_SEED_COUNT
        else _CP_DENOMINATOR - _lower_cp_numerator(CP68_TEST28_SEED_COUNT - k)
    )
    return (
        Fraction(lower_numerator, _CP_DENOMINATOR),
        Fraction(upper_numerator, _CP_DENOMINATOR),
    )


def cp68_exact_clopper_pearson_interval_2048(
    success_count: object,
) -> Tuple[Fraction, Fraction]:
    """Return the closed exact n=2048 interval for an integer success count."""

    if type(success_count) is not int:
        raise TypeError("success_count must be an exact integer")
    if not 0 <= cast(int, success_count) <= CP68_TEST28_SEED_COUNT:
        raise ValueError("success_count is outside the frozen range 0..2048")
    return _exact_clopper_pearson_interval(cast(int, success_count))


def _feature_interval(
    mean: Fraction,
    lower: Fraction,
    upper: Fraction,
    selected_count: int,
) -> Optional[Tuple[Fraction, Fraction]]:
    if (
        type(mean) is not Fraction
        or type(lower) is not Fraction
        or type(upper) is not Fraction
    ):
        raise TypeError("CP68 feature interval values must be exact Fractions")
    if type(selected_count) is not int:
        raise TypeError("selected_count must be an exact integer")
    if not 0 <= selected_count <= CP68_TEST28_SEED_COUNT:
        raise ValueError("selected_count is outside the frozen range 0..2048")
    if lower > upper or not lower <= mean <= upper:
        raise ValueError("feature mean or bounds differ from the closed contract")
    if selected_count < CP68_TEST28_MINIMUM_SELECTED_COUNT:
        return None
    halfwidth = (upper - lower) * CP68_TEST28_FEATURE_HALFWIDTH_RANGE_MULTIPLIER
    return max(lower, mean - halfwidth), min(upper, mean + halfwidth)


