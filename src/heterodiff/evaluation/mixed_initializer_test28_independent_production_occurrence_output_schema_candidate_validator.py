def _dependency_ancestors(
    artifact_id: str, dependencies: Mapping[str, Tuple[str, ...]]
) -> Tuple[str, ...]:
    pending = list(dependencies[artifact_id])
    result = set()
    while pending:
        current = pending.pop()
        if current not in result:
            result.add(current)
            pending.extend(dependencies[current])
    return tuple(result)


def _validate_occurrence_semantics(value: dict, expected: dict) -> None:
    for name in (
        "lifecycle_branch_rules",
        "crash_cut_rules",
        "artifact_occurrence_rules",
    ):
        if value[name] != expected[name]:
            _fail(
                "CP74_INPUT_OCCURRENCE_MISMATCH",
                "candidate occurrence descriptor differs for " + name,
            )
    contract = cast(dict, value["contract"])
    artifact_ids = tuple(cast(list, contract["artifact_ids"]))
    branch_ids = tuple(cast(list, contract["lifecycle_branch_ids"]))
    occurrences = cast(list, value["artifact_occurrence_rules"])
    occurrence_by_id = {
        cast(str, row["artifact_id"]): cast(dict, row) for row in occurrences
    }
    dependencies = {
        artifact_id: tuple(
            cast(
                list,
                occurrence_by_id[artifact_id]["dependency_predecessor_artifact_ids"],
            )
        )
        for artifact_id in artifact_ids
    }
    for artifact_id, predecessors in dependencies.items():
        if (
            artifact_id in predecessors
            or len(predecessors) != len(set(predecessors))
            or not set(predecessors) <= set(artifact_ids)
        ):
            _fail("CP74_INPUT_OCCURRENCE_MISMATCH", "artifact dependency differs")
    indegree = {artifact_id: 0 for artifact_id in artifact_ids}
    outgoing = {artifact_id: [] for artifact_id in artifact_ids}
    for target, predecessors in dependencies.items():
        for source in predecessors:
            outgoing[source].append(target)
            indegree[target] += 1
    frontier = [item for item in artifact_ids if indegree[item] == 0]
    visited = 0
    while frontier:
        source = frontier.pop()
        visited += 1
        for target in outgoing[source]:
            indegree[target] -= 1
            if indegree[target] == 0:
                frontier.append(target)
    if visited != len(artifact_ids):
        _fail("CP74_INPUT_OCCURRENCE_MISMATCH", "artifact dependency graph is cyclic")
    lifecycle_by_id = {
        cast(str, row["branch_id"]): cast(dict, row)
        for row in cast(list, value["lifecycle_branch_rules"])
    }
    for branch_id in branch_ids:
        expressions = {
            artifact_id: dict(
                cast(
                    list, occurrence_by_id[artifact_id]["branch_occurrence_expressions"]
                )
            )[branch_id]
            for artifact_id in artifact_ids
        }
        lifecycle = lifecycle_by_id[branch_id]
        exact = tuple(
            artifact_id
            for artifact_id in artifact_ids
            if expressions[artifact_id] in ("EXACT_GLOBAL_ONE", "EXACT_ALL_32_SHARDS")
        )
        absent = tuple(
            artifact_id
            for artifact_id in artifact_ids
            if expressions[artifact_id] == "ABSENT"
        )
        prefix = tuple(
            artifact_id
            for artifact_id in artifact_ids
            if expressions[artifact_id] == "DURABLE_PREFIX_DEPENDENCY_CLOSED"
        )
        if (
            tuple(cast(list, lifecycle["always_required_artifact_ids"])) != exact
            or tuple(cast(list, lifecycle["always_forbidden_artifact_ids"])) != absent
            or tuple(cast(list, lifecycle["durable_prefix_artifact_ids"])) != prefix
        ):
            _fail("CP74_INPUT_OCCURRENCE_MISMATCH", "lifecycle projection differs")
        for artifact_id, expression in expressions.items():
            if expression != "ABSENT" and any(
                expressions[ancestor] == "ABSENT"
                for ancestor in _dependency_ancestors(artifact_id, dependencies)
            ):
                _fail(
                    "CP74_INPUT_OCCURRENCE_MISMATCH",
                    "branch dependency closure differs",
                )
    for cut in cast(list, value["crash_cut_rules"]):
        checked = cast(dict, cut)
        required = set(cast(list, checked["required_durable_artifact_ids"]))
        forbidden = set(cast(list, checked["forbidden_artifact_ids"]))
        conditional = set(cast(list, checked["conditional_artifact_ids"]))
        if required & forbidden or conditional & forbidden:
            _fail("CP74_INPUT_OCCURRENCE_MISMATCH", "crash-cut sets overlap")
        ancestors = {
            ancestor
            for artifact_id in required
            for ancestor in _dependency_ancestors(artifact_id, dependencies)
        }
        if ancestors & forbidden:
            _fail(
                "CP74_INPUT_OCCURRENCE_MISMATCH",
                "crash-cut dependency closure intersects its forbidden set",
            )
    manifest_false = tuple(
        artifact_id
        for artifact_id in artifact_ids
        if not occurrence_by_id[artifact_id]["manifest_bound_if_present"]
    )
    committed_false = tuple(
        artifact_id
        for artifact_id in artifact_ids
        if not occurrence_by_id[artifact_id][
            "committed_marker_transitively_binds_if_present"
        ]
    )
    if manifest_false != (
        "sha256-manifest",
        "committed-marker",
        "auxiliary-reservation-transition-journal",
    ) or committed_false != ("committed-marker",):
        _fail("CP74_INPUT_OCCURRENCE_MISMATCH", "publication binding flags differ")


def _field_grammar_paths(rules: list) -> Tuple[str, ...]:
    result = []
    for rule in rules:
        if cast(str, rule).startswith("field-grammar|path="):
            parts = cast(str, rule).split("|", 3)
            if (
                len(parts) != 4
                or not parts[1].startswith("path=/")
                or not parts[2].startswith("json-type=")
                or not parts[3].startswith("constraint=")
            ):
                _fail(
                    "CP74_INPUT_OUTPUT_SEMANTIC_MISMATCH",
                    "field grammar token is malformed",
                )
            result.append(parts[1][5:])
    return tuple(result)


