def _account_canonical_text(
    value: str, text_characters: List[int], *, key: bool = False
) -> None:
    item_limit = (
        CP74_INDEPENDENT_TEST28_MAXIMUM_KEY_CHARACTERS
        if key
        else CP74_INDEPENDENT_TEST28_MAXIMUM_TEXT_ITEM_CHARACTERS
    )
    if len(value) > item_limit:
        raise ValueError("independent CP74 canonical text exceeds its item limit")
    text_characters[0] += len(value)
    if text_characters[0] > CP74_INDEPENDENT_TEST28_MAXIMUM_DECODED_TEXT_CHARACTERS:
        raise ValueError("independent CP74 canonical text exceeds its total limit")


def _primitive(
    value: object,
    *,
    depth: int = 0,
    nodes: Optional[List[int]] = None,
    text_characters: Optional[List[int]] = None,
) -> object:
    if nodes is None:
        nodes = [0]
    if text_characters is None:
        text_characters = [0]
    nodes[0] += 1
    if (
        depth > CP74_INDEPENDENT_TEST28_MAXIMUM_JSON_DEPTH
        or nodes[0] > CP74_INDEPENDENT_TEST28_MAXIMUM_JSON_NODES
    ):
        raise ValueError("independent CP74 canonical value exceeds its limit")
    if value is None or type(value) is bool:
        return value
    if type(value) is int:
        if (
            abs(cast(int, value))
            >= 10**CP74_INDEPENDENT_TEST28_MAXIMUM_INTEGER_DECIMAL_DIGITS
        ):
            raise ValueError("independent CP74 canonical integer exceeds its limit")
        return value
    if type(value) is str:
        _account_canonical_text(cast(str, value), text_characters)
        return value
    if isinstance(value, _SealedRecord):
        record_fields = fields(value)
        if len(record_fields) > CP74_INDEPENDENT_TEST28_MAXIMUM_OBJECT_MEMBERS:
            raise ValueError("independent CP74 record has too many fields")
        for item in record_fields:
            _account_canonical_text(item.name, text_characters, key=True)
        return {
            item.name: _primitive(
                getattr(value, item.name),
                depth=depth + 1,
                nodes=nodes,
                text_characters=text_characters,
            )
            for item in record_fields
        }
    if type(value) is tuple:
        items = cast(tuple, value)
        if len(items) > CP74_INDEPENDENT_TEST28_MAXIMUM_ARRAY_ITEMS:
            raise ValueError("independent CP74 tuple exceeds its item limit")
        return [
            _primitive(
                item,
                depth=depth + 1,
                nodes=nodes,
                text_characters=text_characters,
            )
            for item in items
        ]
    if type(value) is list:
        items = cast(list, value)
        if len(items) > CP74_INDEPENDENT_TEST28_MAXIMUM_ARRAY_ITEMS:
            raise ValueError("independent CP74 list exceeds its item limit")
        return [
            _primitive(
                item,
                depth=depth + 1,
                nodes=nodes,
                text_characters=text_characters,
            )
            for item in items
        ]
    if type(value) is dict:
        mapping = cast(dict, value)
        if len(mapping) > CP74_INDEPENDENT_TEST28_MAXIMUM_OBJECT_MEMBERS:
            raise ValueError("independent CP74 mapping exceeds its member limit")
        if any(type(key) is not str for key in mapping):
            raise TypeError("independent CP74 mapping keys must be exact text")
        for key in mapping:
            _account_canonical_text(key, text_characters, key=True)
        return {
            key: _primitive(
                mapping[key],
                depth=depth + 1,
                nodes=nodes,
                text_characters=text_characters,
            )
            for key in mapping
        }
    raise TypeError("unsupported independent CP74 canonical value")


def _typed_snapshot(
    value: object,
    *,
    root_record: bool = False,
    depth: int = 0,
    nodes: Optional[List[int]] = None,
    text_characters: Optional[List[int]] = None,
) -> object:
    if nodes is None:
        nodes = [0]
    if text_characters is None:
        text_characters = [0]
    nodes[0] += 1
    if (
        depth > CP74_INDEPENDENT_TEST28_MAXIMUM_JSON_DEPTH
        or nodes[0] > CP74_INDEPENDENT_TEST28_MAXIMUM_JSON_NODES
    ):
        raise ValueError("independent CP74 typed snapshot exceeds its limit")
    if value is None or type(value) is bool:
        return (type(value),)
    if type(value) is int:
        if (
            abs(cast(int, value))
            >= 10**CP74_INDEPENDENT_TEST28_MAXIMUM_INTEGER_DECIMAL_DIGITS
        ):
            raise ValueError("independent CP74 typed integer exceeds its limit")
        return (type(value),)
    if type(value) is str:
        _account_canonical_text(cast(str, value), text_characters)
        return (type(value),)
    if isinstance(value, _SealedRecord):
        if type(value) not in _RECORD_DOMAINS:
            raise TypeError("unsupported independent CP74 record type")
        identity = None if root_record else value
        record_fields = fields(value)
        if len(record_fields) > CP74_INDEPENDENT_TEST28_MAXIMUM_OBJECT_MEMBERS:
            raise ValueError("independent CP74 typed record has too many fields")
        for item in record_fields:
            _account_canonical_text(item.name, text_characters, key=True)
        return (
            "record",
            type(value),
            identity,
            tuple(
                (
                    item.name,
                    _typed_snapshot(
                        getattr(value, item.name),
                        depth=depth + 1,
                        nodes=nodes,
                        text_characters=text_characters,
                    ),
                )
                for item in record_fields
            ),
        )
    if type(value) is tuple:
        items = cast(tuple, value)
        if len(items) > CP74_INDEPENDENT_TEST28_MAXIMUM_ARRAY_ITEMS:
            raise ValueError("independent CP74 typed tuple exceeds its item limit")
        return (
            "tuple",
            tuple(
                _typed_snapshot(
                    item,
                    depth=depth + 1,
                    nodes=nodes,
                    text_characters=text_characters,
                )
                for item in items
            ),
        )
    if type(value) is list:
        items = cast(list, value)
        if len(items) > CP74_INDEPENDENT_TEST28_MAXIMUM_ARRAY_ITEMS:
            raise ValueError("independent CP74 typed list exceeds its item limit")
        return (
            "list",
            tuple(
                _typed_snapshot(
                    item,
                    depth=depth + 1,
                    nodes=nodes,
                    text_characters=text_characters,
                )
                for item in items
            ),
        )
    if type(value) is dict:
        mapping = cast(dict, value)
        if len(mapping) > CP74_INDEPENDENT_TEST28_MAXIMUM_OBJECT_MEMBERS:
            raise ValueError("independent CP74 typed mapping exceeds its member limit")
        if any(type(key) is not str for key in mapping):
            raise TypeError("independent CP74 typed snapshot keys must be exact text")
        for key in mapping:
            _account_canonical_text(key, text_characters, key=True)
        return (
            "dict",
            tuple(
                (
                    key,
                    _typed_snapshot(
                        mapping[key],
                        depth=depth + 1,
                        nodes=nodes,
                        text_characters=text_characters,
                    ),
                )
                for key in mapping
            ),
        )
    raise TypeError("unsupported independent CP74 typed snapshot value")


def _plain_json_bytes(value: object) -> bytes:
    return json.dumps(
        _primitive(value),
        sort_keys=True,
        separators=(",", ":"),
        ensure_ascii=True,
        allow_nan=False,
    ).encode("ascii")


def _record(cls: type, values: Mapping[str, object]) -> object:
    names = tuple(item.name for item in fields(cls))
    if tuple(values) != tuple(name for name in names if name != "record_sha256"):
        raise RuntimeError("independent CP74 record construction fields differ")
    instance = object.__new__(cls)
    for name in names:
        object.__setattr__(
            instance, name, "0" * 64 if name == "record_sha256" else values[name]
        )
    digest = hashlib.sha256(
        _RECORD_DOMAINS[cls] + _plain_json_bytes(instance)
    ).hexdigest()
    object.__setattr__(instance, "record_sha256", digest)
    snapshot = _plain_json_bytes(instance)
    typed_snapshot = _typed_snapshot(instance, root_record=True)
    with _ISSUED_RECORD_LOCK:
        _ISSUED_RECORD_SNAPSHOTS[instance] = (snapshot, typed_snapshot)
    return instance


