def _is_sha256(value: object) -> bool:
    return (
        type(value) is str
        and re.fullmatch(r"[0-9a-f]{64}", cast(str, value)) is not None
    )


def _reject_duplicate_pairs(pairs: list) -> dict:
    result = {}
    for key, value in pairs:
        if key in result:
            _fail("CP74_INPUT_JSON_INVALID", "JSON contains a duplicate key")
        result[key] = value
    return result


def _parse_bounded_integer(text: str) -> int:
    digits = text[1:] if text.startswith("-") else text
    if len(digits) > CP74_INDEPENDENT_TEST28_MAXIMUM_INTEGER_DECIMAL_DIGITS:
        _fail("CP74_INPUT_RESOURCE_LIMIT", "JSON integer text exceeds its cap")
    try:
        return int(text, 10)
    except ValueError as exc:
        raise CP74IndependentValidationError(
            "CP74_INPUT_JSON_INVALID", "JSON integer text is invalid"
        ) from exc


def _reject_json_float(_text: str) -> object:
    _fail("CP74_INPUT_JSON_INVALID", "JSON floating values are forbidden")
    raise AssertionError("unreachable")


def _walk_decoded(
    value: object,
    *,
    depth: int = 0,
    nodes: Optional[List[int]] = None,
    text_characters: Optional[List[int]] = None,
) -> None:
    if nodes is None:
        nodes = [0]
    if text_characters is None:
        text_characters = [0]
    nodes[0] += 1
    if depth > CP74_INDEPENDENT_TEST28_MAXIMUM_JSON_DEPTH:
        _fail("CP74_INPUT_RESOURCE_LIMIT", "decoded JSON nesting exceeds its cap")
    if nodes[0] > CP74_INDEPENDENT_TEST28_MAXIMUM_JSON_NODES:
        _fail("CP74_INPUT_RESOURCE_LIMIT", "decoded JSON node count exceeds its cap")
    if value is None or type(value) is bool:
        return
    if type(value) is int:
        if (
            len(str(abs(cast(int, value))))
            > CP74_INDEPENDENT_TEST28_MAXIMUM_INTEGER_DECIMAL_DIGITS
        ):
            _fail("CP74_INPUT_RESOURCE_LIMIT", "decoded integer exceeds its cap")
        return
    if type(value) is str:
        checked_text = cast(str, value)
        if any(0xD800 <= ord(character) <= 0xDFFF for character in checked_text):
            _fail("CP74_INPUT_ENCODING_INVALID", "decoded text contains a surrogate")
        length = len(checked_text)
        if length > CP74_INDEPENDENT_TEST28_MAXIMUM_TEXT_ITEM_CHARACTERS:
            _fail("CP74_INPUT_RESOURCE_LIMIT", "decoded text item exceeds its cap")
        text_characters[0] += length
        if text_characters[0] > CP74_INDEPENDENT_TEST28_MAXIMUM_DECODED_TEXT_CHARACTERS:
            _fail("CP74_INPUT_RESOURCE_LIMIT", "decoded text total exceeds its cap")
        return
    if type(value) is list:
        items = cast(list, value)
        if len(items) > CP74_INDEPENDENT_TEST28_MAXIMUM_ARRAY_ITEMS:
            _fail("CP74_INPUT_RESOURCE_LIMIT", "decoded array exceeds its cap")
        for item in items:
            _walk_decoded(
                item,
                depth=depth + 1,
                nodes=nodes,
                text_characters=text_characters,
            )
        return
    if type(value) is dict:
        mapping = cast(dict, value)
        if len(mapping) > CP74_INDEPENDENT_TEST28_MAXIMUM_OBJECT_MEMBERS:
            _fail("CP74_INPUT_RESOURCE_LIMIT", "decoded object exceeds its cap")
        for key, item in mapping.items():
            if type(key) is not str:
                _fail("CP74_INPUT_FIELD_TYPE_MISMATCH", "decoded key is not text")
            if any(0xD800 <= ord(character) <= 0xDFFF for character in key):
                _fail("CP74_INPUT_ENCODING_INVALID", "decoded key contains a surrogate")
            if len(key) > CP74_INDEPENDENT_TEST28_MAXIMUM_KEY_CHARACTERS:
                _fail("CP74_INPUT_RESOURCE_LIMIT", "decoded key exceeds its cap")
            text_characters[0] += len(key)
            if (
                text_characters[0]
                > CP74_INDEPENDENT_TEST28_MAXIMUM_DECODED_TEXT_CHARACTERS
            ):
                _fail("CP74_INPUT_RESOURCE_LIMIT", "decoded text total exceeds its cap")
            _walk_decoded(
                item,
                depth=depth + 1,
                nodes=nodes,
                text_characters=text_characters,
            )
        return
    _fail("CP74_INPUT_FIELD_TYPE_MISMATCH", "decoded value has an alien type")


def _preflight_json_nesting(text: str) -> None:
    depth = 0
    in_string = False
    escaped = False
    for character in text:
        if in_string:
            if escaped:
                escaped = False
            elif character == "\\":
                escaped = True
            elif character == '"':
                in_string = False
            continue
        if character == '"':
            in_string = True
        elif character in "[{":
            depth += 1
            if depth > CP74_INDEPENDENT_TEST28_MAXIMUM_JSON_DEPTH:
                _fail("CP74_INPUT_RESOURCE_LIMIT", "JSON nesting exceeds its cap")
        elif character in "]}" and depth:
            depth -= 1


def _decode_candidate_payload(payload: object) -> Tuple[dict, bytes]:
    if type(payload) is not bytes:
        _fail("CP74_INPUT_TYPE_MISMATCH", "candidate payload must be exact bytes")
    encoded = cast(bytes, payload)
    if not encoded or len(encoded) > CP74_INDEPENDENT_TEST28_MAXIMUM_INPUT_BYTES:
        _fail("CP74_INPUT_BYTE_LIMIT", "candidate payload byte length is invalid")
    if encoded.startswith(b"\xef\xbb\xbf"):
        _fail("CP74_INPUT_ENCODING_INVALID", "candidate payload has a BOM")
    try:
        text = encoded.decode("ascii")
    except UnicodeDecodeError as exc:
        raise CP74IndependentValidationError(
            "CP74_INPUT_ENCODING_INVALID", "candidate payload is not ASCII"
        ) from exc
    if len(text) > CP74_INDEPENDENT_TEST28_MAXIMUM_DECODED_TEXT_CHARACTERS:
        _fail("CP74_INPUT_RESOURCE_LIMIT", "decoded payload text exceeds its cap")
    _preflight_json_nesting(text)
    try:
        value = json.loads(
            text,
            object_pairs_hook=_reject_duplicate_pairs,
            parse_float=_reject_json_float,
            parse_int=_parse_bounded_integer,
            parse_constant=_reject_json_float,
        )
    except CP74IndependentValidationError:
        raise
    except RecursionError as exc:
        raise CP74IndependentValidationError(
            "CP74_INPUT_RESOURCE_LIMIT", "candidate JSON parser recursion was bounded"
        ) from exc
    except (json.JSONDecodeError, ValueError) as exc:
        raise CP74IndependentValidationError(
            "CP74_INPUT_JSON_INVALID", "candidate payload JSON is invalid"
        ) from exc
    _walk_decoded(value)
    if type(value) is not dict:
        _fail("CP74_INPUT_FIELD_TYPE_MISMATCH", "candidate root is not an object")
    try:
        replay = _plain_json_bytes(value)
    except (RecursionError, TypeError, ValueError) as exc:
        raise CP74IndependentValidationError(
            "CP74_INPUT_CANONICAL_MISMATCH", "candidate payload cannot be replayed"
        ) from exc
    if replay != encoded:
        _fail("CP74_INPUT_CANONICAL_MISMATCH", "candidate payload is not canonical")
    return cast(dict, value), encoded


def _embedded_authoritative_bundle() -> Tuple[dict, bytes]:
    try:
        raw = zlib.decompress(
            base64.b64decode(_AUTHORITATIVE_BUNDLE_ZLIB_B64, validate=True)
        )
        value = json.loads(raw.decode("ascii"))
    except (ValueError, UnicodeDecodeError, json.JSONDecodeError, zlib.error) as exc:
        raise RuntimeError("embedded authoritative candidate is invalid") from exc
    if (
        type(value) is not dict
        or len(raw) != _AUTHORITATIVE_BUNDLE_CANONICAL_JSON_BYTES
        or _plain_json_bytes(value) != raw
        or value.get("record_sha256") != _AUTHORITATIVE_BUNDLE_RECORD_SHA256
        or value.get("candidate_schema_semantic_sha256")
        != _CANDIDATE_SCHEMA_SEMANTIC_SHA256
    ):
        raise RuntimeError("embedded authoritative candidate identity differs")
    public = hashlib.sha256(
        _AUTHORITATIVE_PUBLIC_RECORD_DOMAIN
        + _AUTHORITATIVE_BUNDLE_CLASS_NAME.encode("ascii")
        + b"\0"
        + raw
    ).hexdigest()
    if public != _AUTHORITATIVE_BUNDLE_PUBLIC_SHA256:
        raise RuntimeError("embedded authoritative public digest differs")
    return cast(dict, value), raw


def _validate_shape(value: object, expected: object, path: str = "$") -> None:
    if type(value) is not type(expected):
        _fail(
            "CP74_INPUT_FIELD_TYPE_MISMATCH",
            "candidate value type differs at " + path,
        )
    if type(value) is dict:
        supplied = cast(dict, value)
        wanted = cast(dict, expected)
        if set(supplied) != set(wanted):
            _fail(
                "CP74_INPUT_FIELD_SET_MISMATCH",
                "candidate field set differs at " + path,
            )
        for key in wanted:
            _validate_shape(supplied[key], wanted[key], path + "/" + key)
    elif type(value) is list:
        supplied_items = cast(list, value)
        wanted_items = cast(list, expected)
        for index in range(min(len(supplied_items), len(wanted_items))):
            _validate_shape(
                supplied_items[index],
                wanted_items[index],
                path + "/" + str(index),
            )


